// --- Haberleşme Fonksiyonları ---
static void ssd1306_WriteCommand(uint8_t command) {
    HAL_I2C_Mem_Write(&hi2c1, SSD1306_I2C_ADDR, 0x00, 1, &command, 1, 10);
}

void ssd1306_Init(void) {
    HAL_Delay(100);
    ssd1306_WriteCommand(0xAE); // Display OFF
    ssd1306_WriteCommand(0x20); // Addressing Mode
    ssd1306_WriteCommand(0x10); // Page Mode
    ssd1306_WriteCommand(0xA8); // Multiplex Ratio
    ssd1306_WriteCommand(0x1F); // 32 line (0.91" OLED)
    ssd1306_WriteCommand(0xD3); // Display Offset
    ssd1306_WriteCommand(0x00);
    ssd1306_WriteCommand(0x40); // Start Line
    ssd1306_WriteCommand(0xA1); // Segment Re-map
    ssd1306_WriteCommand(0xC8); // COM Scan Direction
    ssd1306_WriteCommand(0xDA); // COM Pins
    ssd1306_WriteCommand(0x02);
    ssd1306_WriteCommand(0x81); // Contrast
    ssd1306_WriteCommand(0x7F);
    ssd1306_WriteCommand(0xA4); // Entire Display ON
    ssd1306_WriteCommand(0xA6); // Normal Display
    ssd1306_WriteCommand(0xD5); // Osc Frequency
    ssd1306_WriteCommand(0x80);
    ssd1306_WriteCommand(0x8D); // Charge Pump
    ssd1306_WriteCommand(0x14);
    ssd1306_WriteCommand(0xAF); // Display ON
    ssd1306_Fill(Black);
    ssd1306_UpdateScreen();
}

void ssd1306_Fill(SSD1306_COLOR color) {
    for(int i = 0; i < sizeof(SSD1306_Buffer); i++) {
        SSD1306_Buffer[i] = (color == Black) ? 0x00 : 0xFF;
    }
}

void ssd1306_UpdateScreen(void) {
    for (uint8_t i = 0; i < 4; i++) {
        ssd1306_WriteCommand(0xB0 + i);
        ssd1306_WriteCommand(0x00);
        ssd1306_WriteCommand(0x10);
        HAL_I2C_Mem_Write(&hi2c1, SSD1306_I2C_ADDR, 0x40, 1, &SSD1306_Buffer[SSD1306_WIDTH * i], SSD1306_WIDTH, 100);
    }
}

void ssd1306_SetCursor(uint8_t x, uint8_t y) {
    CurrentX = x;
    CurrentY = y;
}

void ssd1306_WriteChar(char ch, FontDef font, SSD1306_COLOR color) {
    if (ch < 32 || ch > 126) return;

    // --- HARF KAYMASI DÜZELTMESİ ---
    // Eğer a yazdığında g çıkıyorsa, küçük harf başladığında (97 ve sonrası)
    // tabloyu 6 karakter geri çekmemiz gerekir.
    uint32_t char_index;
    if (ch >= 97 && ch <= 122) {
        char_index = (ch - 32) - 6; // 6 karakterlik kaymayı telafi et
    } else {
        char_index = (ch - 32);
    }

    for (uint32_t i = 0; i < font.height; i++) {
        // char_index kullanarak tablodan doğru veriyi çekiyoruz
        uint16_t b = font.data[char_index * font.height + i] << 1;

        for (uint32_t j = 0; j < font.width; j++) {
            if ((b << j) & 0x8000) {
                int pixelX = CurrentX + i;
                int pixelY = CurrentY + (font.width - 1 - j);

                if (pixelX < SSD1306_WIDTH && pixelY < SSD1306_HEIGHT) {
                    if(color == White)
                        SSD1306_Buffer[pixelX + (pixelY / 8) * SSD1306_WIDTH] |= (1 << (pixelY % 8));
                    else
                        SSD1306_Buffer[pixelX + (pixelY / 8) * SSD1306_WIDTH] &= ~(1 << (pixelY % 8));
                }
            }
        }
    }
    CurrentX += font.height + 0;
}

void ssd1306_WriteString(char* str, FontDef font, SSD1306_COLOR color) {
    while (*str) {
        ssd1306_WriteChar(*str, font, color);
        str++;
    }
}
